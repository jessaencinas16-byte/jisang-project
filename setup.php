<?php if (!$confirmed): ?>
  <p class="muted">Ito ay magse-setup ng buong <code>brewpos</code> database mo sa MySQL (XAMPP) mula sa <code>brewpos_schema.sql</code>.</p>
  <div class="warn-box">
    ⚠️ <b>Babala:</b> kung may <code>brewpos</code> database ka nang existing, ide-drop at gagawin ulit nito ang LAHAT ng tables (users, products, orders, atbp.) — mawawala ang anumang datos na dati mo nang naidagdag. Kung bago ka pa lang, walang problema.
  </div>
  <a class="btn" href="?confirm=yes">Sige, gawin ang database</a>
<?php else: ?>
  <?php
  try {
      $mysqli = new mysqli($DB_HOST, $DB_USER, $DB_PASS);
      if ($mysqli->connect_errno) {
          throw new Exception('Hindi makakonekta sa MySQL: ' . $mysqli->connect_error . ' — siguraduhing "Start" ang MySQL sa XAMPP Control Panel.');
      }

      $sqlFile = __DIR__ . '/brewpos_schema.sql';
      if (!file_exists($sqlFile)) {
          throw new Exception('Hindi nakita ang brewpos_schema.sql sa parehong folder ng setup.php. I-upload din ito doon: ' . __DIR__);
      }
      $sql = file_get_contents($sqlFile);
      if ($sql === false || trim($sql) === '') {
          throw new Exception('Walang laman o hindi mabasa ang brewpos_schema.sql.');
      }

      if (!$mysqli->multi_query($sql)) {
          throw new Exception('SQL error: ' . $mysqli->error);
      }
      // Drain every result set generated by the script so multi_query finishes cleanly.
      do {
          if ($result = $mysqli->store_result()) { $result->free(); }
      } while ($mysqli->more_results() && $mysqli->next_result());

      if ($mysqli->errno) {
          throw new Exception('SQL error habang running: ' . $mysqli->error);
      }

      // Quick sanity check — count rows in a couple of tables.
      $mysqli->select_db('brewpos');
      $userCount = $mysqli->query("SELECT COUNT(*) c FROM users")->fetch_assoc()['c'];
      $productCount = $mysqli->query("SELECT COUNT(*) c FROM products")->fetch_assoc()['c'];

      echo '<p class="ok">✅ Tagumpay! Gumana ang "brewpos" database.</p>';
      echo "<ul><li>{$userCount} staff accounts</li><li>{$productCount} products</li><li>Customers, inventory, at promotions — seeded na rin</li></ul>";
      echo '<div class="warn-box">🔒 Ngayon, burahin o palitan ng pangalan ang <code>setup.php</code> file na ito bago mo ipakita ang site sa iba — hindi ito dapat naka-open sa publiko.</div>';
      echo '<a class="btn" href="index.html">Pumunta sa BrewPOS →</a>';

      $mysqli->close();
  } catch (Exception $e) {
      echo '<p class="err">❌ May error: ' . htmlspecialchars($e->getMessage()) . '</p>';
      echo '<a class="btn" href="setup.php">Ulitin</a>';
  }
  ?>
<?php endif; ?>

