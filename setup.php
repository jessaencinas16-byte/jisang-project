   folder) sa htdocs/brewpos/, buksan sa browser:
     http://localhost/brewpos/setup.php
   Gagawa ito ng "brewpos" database + lahat ng tables +
   demo data — hindi mo na kailangang pumunta sa phpMyAdmin.

   ⚠️ WARNING: Ide-drop at gagawin ulit nito ang lahat ng
   tables kapag pinatakbo — kaya kung may totoo ka nang mga
   order/customer na naidagdag, i-back up muna bago ulit
   patakbuhin ito. Ligtas patakbuhin paulit-ulit habang
   nagse-setup/nagte-test ka pa lang.

   🔒 Pagkatapos gumana, BURAHIN o palitan ng pangalan ang
   file na ito (hal. setup.php.bak) — hindi ito dapat
   naka-publicly-accessible kapag live na ang shop mo.
   ===================================================== */

$DB_HOST = 'localhost';
$DB_USER = 'root';
$DB_PASS = ''; // XAMPP default — palitan kung nag-set ka ng sarili mong MySQL password

header('Content-Type: text/html; charset=utf-8');
$confirmed = isset($_GET['confirm']) && $_GET['confirm'] === 'yes';
?>
